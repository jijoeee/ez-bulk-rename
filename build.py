"""Build EZ Bulk Rename for release.

    python build.py            test, build the app folder, then the installer
    python build.py --no-tests skip the test run
    python build.py --no-installer

Steps:
  1. Run the engine tests (a broken build never ships).
  2. Stamp the version from ezrename/__init__.py into the .exe (File > Properties).
  3. Build dist/EZ Bulk Rename/ with PyInstaller (onedir, windowed).
  4. Copy every dependency's licence file into the build (legal requirement).
  5. Build the installer with Inno Setup if it is installed.
  6. Zip the app folder as a portable version (no install needed).
  7. Print SHA-256 checksums and write a Windows Sandbox test file.
"""

from __future__ import annotations

import argparse
import glob
import hashlib
import os
import re
import shutil
import subprocess
import sys
from importlib import metadata

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)

from ezrename import APP_NAME, COPYRIGHT, PUBLISHER, WEBSITE, __version__  # noqa: E402

BUILD = os.path.join(ROOT, "build")
DIST = os.path.join(ROOT, "dist")
APP_DIR = os.path.join(DIST, APP_NAME)
RUNTIME_PACKAGES = ["customtkinter", "tkinterdnd2", "openpyxl", "pillow"]
FILE_STEM = APP_NAME.replace(" ", "-")   # EZ-Bulk-Rename


def step(msg: str) -> None:
    print(f"\n==> {msg}", flush=True)


def run(cmd: list[str]) -> None:
    print("   ", " ".join(f'"{c}"' if " " in c else c for c in cmd), flush=True)
    subprocess.run(cmd, cwd=ROOT, check=True)


# --------------------------------------------------------------- version stamp
def write_version_file() -> str:
    nums = [int(x) for x in re.findall(r"\d+", __version__)[:4]]
    nums += [0] * (4 - len(nums))
    tup = tuple(nums)
    exe = f"{APP_NAME}.exe"
    text = f"""# Generated by build.py from ezrename/__init__.py. Do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={tup}, prodvers={tup}, mask=0x3f, flags=0x0,
                    OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', '{PUBLISHER}'),
      StringStruct('FileDescription', '{APP_NAME}'),
      StringStruct('FileVersion', '{__version__}'),
      StringStruct('InternalName', '{APP_NAME}'),
      StringStruct('LegalCopyright', '{COPYRIGHT}'),
      StringStruct('OriginalFilename', '{exe}'),
      StringStruct('ProductName', '{APP_NAME}'),
      StringStruct('ProductVersion', '{__version__}'),
      StringStruct('Comments', '{WEBSITE}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    os.makedirs(BUILD, exist_ok=True)
    path = os.path.join(BUILD, "version_info.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return path


# --------------------------------------------------------------- licences
def _deps(name: str, seen: set[str]) -> None:
    key = name.lower().replace("_", "-")
    if key in seen:
        return
    try:
        dist = metadata.distribution(name)
    except metadata.PackageNotFoundError:
        return
    seen.add(key)
    for req in dist.requires or []:
        if "extra ==" in req:
            continue
        m = re.match(r"[A-Za-z0-9_.\-]+", req)
        if m:
            _deps(m.group(0), seen)


def bundle_licences() -> int:
    """Copy LICENSE/NOTICE files of every runtime dependency into the build."""
    out = os.path.join(APP_DIR, "licenses")
    shutil.rmtree(out, ignore_errors=True)
    names: set[str] = set()
    for pkg in RUNTIME_PACKAGES:
        _deps(pkg, names)
    count = 0
    for name in sorted(names):
        dist = metadata.distribution(name)
        for f in dist.files or []:
            s = str(f).upper()
            if ".DIST-INFO" not in s or not any(k in s for k in ("LICEN", "COPYING", "NOTICE")):
                continue
            # Some packages ship build licences for every platform; keep Windows ones only
            if "/DATA/" in s.replace("\\", "/") and "WIN" not in s:
                continue
            src = f.locate()
            if os.path.isfile(src):
                rel = str(f).split(".dist-info/", 1)[-1]
                dst = os.path.join(out, f"{dist.metadata['Name']}-{dist.version}", rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copy2(src, dst)
                count += 1
    shutil.copy2(os.path.join(ROOT, "assets", "icons", "LICENSE-lucide.txt"),
                 os.path.join(out, "lucide-icons-LICENSE.txt"))
    py_licence = os.path.join(sys.base_prefix, "LICENSE.txt")
    if os.path.exists(py_licence):
        shutil.copy2(py_licence, os.path.join(out, "python-LICENSE.txt"))
    return count + 1


# --------------------------------------------------------------- signing
def sign(path: str) -> bool:
    """Sign a file if signing is configured, else do nothing.

    Code signing is THE fix for antivirus false positives and SmartScreen warnings.
    Set the EZKERJA_SIGN_CMD environment variable to your signing command, using
    {file} where the file path goes. Examples:

      set EZKERJA_SIGN_CMD=signtool sign /fd SHA256 /tr http://timestamp.digicert.com /td SHA256 /a "{file}"
      set EZKERJA_SIGN_CMD=azuresigntool sign -kvu ... "{file}"

    Until then builds are unsigned, which is expected for a first release.
    """
    template = os.environ.get("EZKERJA_SIGN_CMD")
    if not template:
        return False
    cmd = template.replace("{file}", path)
    print(f"    signing {os.path.basename(path)}")
    result = subprocess.run(cmd, shell=True, cwd=ROOT)
    if result.returncode != 0:
        raise SystemExit(f"Signing failed for {path}. Fix EZKERJA_SIGN_CMD or unset it.")
    return True


# --------------------------------------------------------------- installer
def find_iscc() -> str | None:
    """Locate the Inno Setup compiler (ISCC.exe), whichever version is installed."""
    found = shutil.which("ISCC") or shutil.which("iscc")
    if found:
        return found
    candidates = []
    for var in ("ProgramFiles(x86)", "ProgramFiles", "LOCALAPPDATA"):
        base = os.environ.get(var)
        if not base:
            continue
        # Matches "Inno Setup 6", "Inno Setup 7", and future versions.
        candidates += glob.glob(os.path.join(base, "Inno Setup*", "ISCC.exe"))
        candidates += glob.glob(os.path.join(base, "Programs", "Inno Setup*", "ISCC.exe"))
    # Newest version last in sorted order, so prefer it.
    return sorted(candidates)[-1] if candidates else None


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_sandbox_file() -> str:
    """A Windows Sandbox config that opens a clean Windows with the installer folder mapped."""
    path = os.path.join(DIST, "sandbox-test.wsb")
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"""<Configuration>
  <Networking>Disable</Networking>
  <MappedFolders>
    <MappedFolder>
      <HostFolder>{DIST}</HostFolder>
      <SandboxFolder>C:\\Users\\WDAGUtilityAccount\\Desktop\\release</SandboxFolder>
      <ReadOnly>true</ReadOnly>
    </MappedFolder>
  </MappedFolders>
  <LogonCommand>
    <Command>explorer.exe C:\\Users\\WDAGUtilityAccount\\Desktop\\release</Command>
  </LogonCommand>
</Configuration>
""")
    return path


# --------------------------------------------------------------- portable zip
def write_portable_zip() -> str:
    """The app folder as one zip: unzip and run, nothing to install (USB drives, locked PCs)."""
    base = os.path.join(DIST, f"{FILE_STEM}-{__version__}-portable")
    if os.path.exists(base + ".zip"):
        os.remove(base + ".zip")
    return shutil.make_archive(base, "zip", root_dir=DIST, base_dir=APP_NAME)


# --------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-tests", action="store_true")
    ap.add_argument("--no-installer", action="store_true")
    args = ap.parse_args()

    print(f"Building {APP_NAME} {__version__}")

    if not args.no_tests:
        step("Running tests")
        run([sys.executable, "-m", "pytest", "-q"])

    step("Stamping version")
    print("   ", write_version_file())

    step("Building app folder with PyInstaller")
    run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "ez_bulk_rename.spec"])

    step("Bundling third-party licences")
    print(f"    {bundle_licences()} licence files copied")

    outputs = []
    exe = os.path.join(APP_DIR, APP_NAME + (".exe" if sys.platform == "win32" else ""))
    if os.path.exists(exe):
        outputs.append(exe)
        # Sign the app before it goes into the installer, so both are covered.
        step("Code signing")
        if not sign(exe):
            print("    not configured (EZKERJA_SIGN_CMD is unset) - this build is unsigned")

    if not args.no_installer and sys.platform == "win32":
        iscc = find_iscc()
        if iscc:
            step("Building installer with Inno Setup")
            run([iscc, f"/DAppVersion={__version__}", os.path.join("installer", "installer.iss")])
            setup = os.path.join(DIST, f"{FILE_STEM}-Setup-{__version__}.exe")
            if os.path.exists(setup):
                sign(setup)
                outputs.append(setup)
        else:
            print("\n" + "!" * 68)
            print("  NO INSTALLER WAS BUILT - Inno Setup is not installed.")
            print()
            print("  The app itself built fine. You can run it from:")
            print(f"    {os.path.relpath(APP_DIR, ROOT)}")
            print()
            print("  To get a single-file installer to share with other people:")
            print("    1. Download Inno Setup (free): https://jrsoftware.org/isdl.php")
            print("    2. Install it with the default options.")
            print("    3. Run build.bat again.")
            print("!" * 68)

    if os.path.exists(exe):
        step("Zipping the portable version")
        portable = write_portable_zip()
        print(f"    {os.path.relpath(portable, ROOT)}")
        outputs.append(portable)

    if sys.platform == "win32":
        step("Writing Windows Sandbox test file")
        print("   ", write_sandbox_file())

    step("Done")
    for p in outputs:
        print(f"    {os.path.relpath(p, ROOT)}")
        print(f"      SHA-256 {sha256(p)}")
    print(f"\n    App folder: {os.path.relpath(APP_DIR, ROOT)}")


if __name__ == "__main__":
    main()
